/**
 * Хөтөлбөрийн нэрийг ашиглан дэлгэрэнгүй мэдээлэл авах
 */
export function getProgramDetail(programName: string): ProgramDetail | null {
  return programDetails[programName] || null;
}

/**
 * Бүх хөтөлбөрүүдийн жагсаалт
 */
export function getAllPrograms(): ProgramDetail[] {
  return Object.values(programDetails);
}

/**
 * Зэрэглэлээр нь хөтөлбөрүүдийг шүүх
 */
export function getProgramsByDegree(degree: ProgramDetail["degree"]): ProgramDetail[] {
  return Object.values(programDetails).filter(p => p.degree === degree);
}

